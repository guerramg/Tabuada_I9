def write_all():
    units = list(UNIT_TITLES.keys())
    count = 0
    for grade in range(1, 10):
        for unit in units:
            folder = ROOT / f"ano{grade}" / unit
            folder.mkdir(parents=True, exist_ok=True)

            lesson = make_lesson(grade, unit)
            lesson_path = folder / "lesson.json"
            with open(lesson_path, "w", encoding="utf-8") as f:
                json.dump(lesson, f, ensure_ascii=False, indent=2)
                f.write("\n")
            count += 1

            exercises = build_exercises(grade, unit)
            min_ex = 10 if grade <= 5 else 8
            assert len(exercises) >= min_ex, f"ano{grade}/{unit}: {len(exercises)} < {min_ex}"

            ex_obj = {"unit": unit, "grade": grade, "exercises": exercises}
            ex_path = folder / "exercises.json"
            with open(ex_path, "w", encoding="utf-8") as f:
                json.dump(ex_obj, f, ensure_ascii=False, indent=2)
                f.write("\n")
            count += 1

    print(f"Created {count} files")
    return count


if __name__ == "__main__":
    write_all()
