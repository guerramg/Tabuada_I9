def tmpl(id_, bncc, topic, diff, q, a_min, a_max, b_min, b_max, op, xp=10,
         explain_b=None, explain_g=None):
    ops = {"add": "+", "sub": "−", "mul": "×", "div": "÷"}
    sym = ops[op]
    if explain_b is None:
        explain_b = f"Fechou: {{a}} {sym} {{b}} = {{answer}}. Mandou a real!"
        explain_g = f"Olha só: {{a}} {sym} {{b}} = {{answer}}. Arrasou!"
    return {
        "id": id_, "bncc": bncc, "topic": topic, "difficulty": diff,
        "type": "numeric", "template": True,
        "question_template": q,
        "a_min": a_min, "a_max": a_max, "b_min": b_min, "b_max": b_max,
        "op": op,
        "explain_template_boy": explain_b,
        "explain_template_girl": explain_g,
        "xp": xp,
    }


